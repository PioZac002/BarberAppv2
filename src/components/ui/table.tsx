import * as React from "react"
import { cn } from "@/lib/utils"

/**
 * A table is the directions block on the back of the label: tracked mono
 * headings over a double rule, hairline rules between entries, figures
 * set tabular so columns of times and prices line up on the decimal.
 */
const Table = React.forwardRef<
    HTMLTableElement,
    React.HTMLAttributes<HTMLTableElement>
>(({ className, ...props }, ref) => (
    <div className="relative w-full overflow-x-auto">
        <table
            ref={ref}
            className={cn("w-full caption-bottom text-sm", className)}
            {...props}
        />
    </div>
))
Table.displayName = "Table"

